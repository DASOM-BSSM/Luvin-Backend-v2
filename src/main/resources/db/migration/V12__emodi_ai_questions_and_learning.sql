-- 감정일기(Emodi): AI가 만든 질문(오늘의 밸런스 게임·그룹 질문)과 내가 쓴 글의 학습 반영.
--
-- 1) 기존 테이블(Hibernate ddl-auto가 만든 테이블)은 V7·V11처럼 조건부로만 바꾼다. 빈 DB(CI)에서는 아직 테이블이 없어
--    no-op이고, 이후 Hibernate가 엔티티 정의 그대로 만든다.
--    - daily_questions.question_date: 이 질문이 "오늘의 질문"인 날(KST). 하루 1개라 UNIQUE.
--      예전 seed 질문은 날짜가 없어(null) 더 이상 오늘의 질문으로 나가지 않는다(기존 답변은 그대로 남는다).
--    - daily_questions.source: AI | FALLBACK(AI 실패 시 준비해 둔 대체 질문). seed 질문은 null.
--    - users.learning_enabled: 학습 동의(기본 true). 기존 사용자 행이 있어 DEFAULT로 채운다.
-- 2) 새 테이블은 여기서 만든다. 레거시 테이블(users, diary_room 등)이 Flyway 시점에 없을 수 있어 FK는 걸지 않는다
--    (기존 diary 테이블들과 같은 plain bigint 컬럼 패턴).
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'daily_questions') THEN
        ALTER TABLE daily_questions ADD COLUMN IF NOT EXISTS question_date DATE;
        ALTER TABLE daily_questions ADD COLUMN IF NOT EXISTS source VARCHAR(20);
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uk_daily_questions_question_date') THEN
            ALTER TABLE daily_questions ADD CONSTRAINT uk_daily_questions_question_date UNIQUE (question_date);
        END IF;
    END IF;

    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'users') THEN
        ALTER TABLE users ADD COLUMN IF NOT EXISTS learning_enabled BOOLEAN NOT NULL DEFAULT TRUE;
    END IF;
END $$;

-- 그룹(공유방) 질문. 그룹당 하루(KST) 1개 — 생성이 실패(FAILED)하면 같은 행을 다시 GENERATING으로 바꿔 재시도한다.
CREATE TABLE room_question (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id       BIGINT       NOT NULL,
    question_date DATE         NOT NULL,
    content       VARCHAR(300),
    status        VARCHAR(20)  NOT NULL CHECK (status IN ('GENERATING', 'READY', 'FAILED')),
    requested_by  BIGINT       NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_room_question_room_date UNIQUE (room_id, question_date)
);
CREATE INDEX ix_room_question_room_created ON room_question (room_id, question_date DESC);

-- 그룹 질문 답. 한 사람당 질문 하나에 1개(다시 보내면 수정).
CREATE TABLE room_question_answer (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT       NOT NULL REFERENCES room_question (id),
    user_id     BIGINT       NOT NULL,
    content     VARCHAR(200) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_room_question_answer_question_user UNIQUE (question_id, user_id)
);

-- 학습 신호: 사용자가 쓴 글(원문은 각 테이블에 그대로 있고 여기는 가리키기만 한다).
-- 말투 학습과 성격 학습이 서로 다른 신호를 따로 소비하므로 소비 시각을 둘로 나눈다(해당 없는 쪽은 null 그대로 둔다).
CREATE TABLE user_learning_signal (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT      NOT NULL,
    source_type             VARCHAR(20) NOT NULL CHECK (source_type IN ('DIARY', 'COMMENT', 'ROOM_ANSWER', 'BALANCE_ANSWER')),
    source_id               BIGINT      NOT NULL,
    created_at              TIMESTAMPTZ NOT NULL,
    speech_consumed_at      TIMESTAMPTZ,
    personality_consumed_at TIMESTAMPTZ,
    CONSTRAINT uk_user_learning_signal_source UNIQUE (source_type, source_id)
);
CREATE INDEX ix_user_learning_signal_user ON user_learning_signal (user_id, created_at);

-- 사용자별 말투 요약(AI 말투 추출 결과를 이전 값과 섞은 것). 에피소드 생성 입력 learnedProfile.speechStyle.
CREATE TABLE user_speech_style (
    user_id      BIGINT PRIMARY KEY,
    style_json   JSONB       NOT NULL,
    update_count INTEGER     NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL
);

-- 사용자별 반죽 성격 보정(설문 점수 위에 더하는 축별 누적 변화량, 1~100 척도).
CREATE TABLE user_personality_adjustment (
    user_id      BIGINT PRIMARY KEY,
    deltas_json  JSONB       NOT NULL,
    update_count INTEGER     NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL
);
